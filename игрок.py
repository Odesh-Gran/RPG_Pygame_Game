def потратить_ресурсы(игрок, сытость_цена=0, жажда_цена=0):
    """
    Тратит сытость и жажду на действие.
    Если ресурсов не хватает - тратит сколько есть и возвращает предупреждение.
    """
    # Тратим сколько есть (не блокируем)
    игрок["сытость"] = max(0, игрок.get("сытость", 0) - сытость_цена)
    игрок["жажда"] = max(0, игрок.get("жажда", 0) - жажда_цена)

    # Проверяем, хватило ли ресурсов
    предупреждение = None
    if игрок.get("сытость", 0) <= 0 and сытость_цена > 0:
        предупреждение = "ЭХ... шас бы поесть!"

    if игрок.get("жажда", 0) <= 0 and жажда_цена > 0:
        предупреждение = "Хочу пить!"

    if предупреждение:
        return False, предупреждение

    return True, f"Потрачено: сытость -{сытость_цена}, жажда -{жажда_цена}"


def восстановить_сытость(игрок, количество):
    """Восстанавливает сытость"""
    макс = игрок.get("макс_сытость", 100)
    игрок["сытость"] = min(макс, игрок.get("сытость", 0) + количество)
    print(f"   🍖 Сытость +{количество} (теперь: {игрок['сытость']})")


def восстановить_жажду(игрок, количество):
    """Восстанавливает жажду"""
    макс = игрок.get("макс_жажда", 100)
    игрок["жажда"] = min(макс, игрок.get("жажда", 0) + количество)
    print(f"   💧 Жажда +{количество} (теперь: {игрок['жажда']})")


def проверить_голод(игрок):
    """Проверяет, не умер ли игрок от голода/жажды"""
    урон = 0
    сообщения = []

    # Проверяем голод
    if игрок.get("сытость", 100) <= 0:
        урон += 7
        сообщения.append("Голод наносит 7 урона!")

    # Проверяем жажду
    if игрок.get("жажда", 100) <= 0:
        урон += 3
        сообщения.append("Жажда наносит 3 урона!")

    # Применяем урон
    if урон > 0:
        игрок["здоровье"] = max(0, игрок.get("здоровье", 0) - урон)
        return True, " ".join(сообщения)

    return False, ""

