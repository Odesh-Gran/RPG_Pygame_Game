def получить_предел_навыка(навык):
    """Возвращает максимальный уровень для указанного навыка"""
    from классы import классы

    класс_игрока = игрок.get("класс")
    if not класс_игрока:
        return 10

    данные_класса = классы.get(класс_игрока, {})
    пределы = данные_класса.get("пределы_навыков", {})
    return пределы.get(навык, 10)


def проверить_и_повысить_навык(навык, повышение=1):
    """Повышает навык с проверкой предела"""
    текущий = игрок.get(навык, 0)
    предел = получить_предел_навыка(навык)

    if текущий >= предел:
        return False, текущий, f"{навык} уже на максимуме ({предел})!"

    новый = min(текущий + повышение, предел)
    игрок[навык] = новый

    повышение_реальное = новый - текущий
    if повышение_реальное > 0:
        return True, новый, f"{навык} +{повышение_реальное}! Теперь: {новый}/{предел}"
    else:
        return False, текущий, f"{навык} не изменился"


