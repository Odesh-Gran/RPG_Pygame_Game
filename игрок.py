def добавить_опыт(количество):
    """
    Добавляет опыт игроку и автоматически проверяет повышение уровня.
    Вызывается везде, где игрок получает опыт.
    """
    global игрок

    # Добавляем опыт
    игрок["опыт"] += количество
    print(f"⭐ Получено {количество} опыта! Всего: {игрок['опыт']}")

    # Проверяем повышение уровня
    проверить_повышение_уровня()


def проверить_повышение_уровня():
    """
    Проверяет, достаточно ли опыта для повышения уровня.
    Автоматически повышает уровень, пока есть достаточно опыта.
    """
    global игрок

    МАКС_УРОВЕНЬ = 100
    уровень_повышен = False

    while игрок["опыт"] >= игрок["опыта_до_след_уровня"] and игрок["уровень"] < МАКС_УРОВЕНЬ:
        уровень_повышен = True

        # Снимаем опыт за текущий уровень
        игрок["опыт"] -= игрок["опыта_до_след_уровня"]

        # Повышаем уровень
        игрок["уровень"] += 1

        # Начисляем очки
        игрок["очки_умений"] = игрок.get("очки_умений", 0) + 1
        игрок["очки_навыков"] = игрок.get("очки_навыков", 0) + 1

        # Рассчитываем опыт до следующего уровня
        игрок["опыта_до_след_уровня"] = int(игрок["опыта_до_след_уровня"] * 2)

        # Восстанавливаем здоровье при повышении уровня
        игрок["здоровье"] = игрок["макс_здоровье"]

        print(f"🎉 ПОВЫШЕНИЕ УРОВНЯ! Теперь уровень {игрок['уровень']}!")
        print(f"📚 Очков умений: {игрок['очки_умений']}, Очков навыков: {игрок['очки_навыков']}")
        print(f"📈 До следующего уровня: {игрок['опыта_до_след_уровня']} опыта")

    # Показываем прогресс, если уровень не повысился
    if not уровень_повышен and игрок["опыт"] > 0:
        прогресс = int((игрок["опыт"] / игрок["опыта_до_след_уровня"]) * 100)
        print(f"📊 Прогресс до следующего уровня: {прогресс}% ({игрок['опыт']}/{игрок['опыта_до_след_уровня']})")

    # Проверка на максимальный уровень
    if игрок["уровень"] >= МАКС_УРОВЕНЬ:
        игрок["опыт"] = 0
        print("🏆 Достигнут максимальный уровень!")


