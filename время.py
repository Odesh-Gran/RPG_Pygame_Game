# время.py
# Система времени для игры

# Глобальный словарь времени
время_в_игре = {
    'час': 8,
    'минута': 0,
    'день': 1,
}


def пройти_время(минута):
    """Проходит указанное количество минут"""
    время_в_игре["минута"] += минута

    # Переводим минуты в часы
    while время_в_игре['минута'] >= 60:
        время_в_игре['минута'] -= 60
        время_в_игре['час'] += 1

    # Переводим часы в дни
    while время_в_игре['час'] >= 24:
        время_в_игре['час'] -= 24
        время_в_игре['день'] += 1


def получить_время_суток():
    """Возвращает строку с временем суток"""
    час = время_в_игре["час"]

    if 6 <= час < 12:
        период = "Утро"
    elif 12 <= час < 18:
        период = "День"
    elif 18 <= час < 22:
        период = "Вечер"
    else:
        период = "Ночь"

    # Форматируем время
    время_строка = f"{время_в_игре['час']:02d}:{время_в_игре['минута']:02d}"

    return f"{период} ({время_строка}) | День {время_в_игре['день']}"


def показать_время():
    """Краткое отображение времени"""
    return f"{время_в_игре['час']:02d}:{время_в_игре['минута']:02d}"


def получить_день():
    """Возвращает текущий игровой день (начиная с 1)"""
    return время_в_игре['день']


def установить_день(день):
    """Устанавливает текущий игровой день"""
    время_в_игре['день'] = день
    print(f"📅 День установлен: {день}")


def установить_час(час):
    """Устанавливает текущий час"""
    время_в_игре['час'] = час


def установить_минуту(минута):
    """Устанавливает текущую минуту"""
    время_в_игре['минута'] = минута


def установить_время(час, минута, день):
    """Полностью устанавливает время игры"""
    время_в_игре['час'] = час
    время_в_игре['минута'] = минута
    время_в_игре['день'] = день
    print(f"🕐 Время установлено: {час:02d}:{минута:02d}, День {день}")


def получить_час():
    """Возвращает текущий час"""
    return время_в_игре['час']


def получить_минуту():
    """Возвращает текущую минуту"""
    return время_в_игре['минута']


def получить_полное_время():
    """Возвращает полную информацию о времени"""
    return {
        'час': время_в_игре['час'],
        'минута': время_в_игре['минута'],
        'день': время_в_игре['день']
    }