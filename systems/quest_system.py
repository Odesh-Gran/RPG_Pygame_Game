    def проверить_ежедневный_квест(self, квест_id, игрок):
        """Проверяет, выполнен ли ежедневный квест"""
        квест = None
        for q in self.ежедневные_квесты:
            if q.get("id") == квест_id:
                квест = q
                break

        if not квест:
            return False

        цели = квест.get("цели", {})
        тип_квеста = квест.get("тип", "")

        прогресс = игрок.get("ежедневные_квесты_прогресс", {}).get(квест_id, {})

        # 👇 УНИВЕРСАЛЬНАЯ ПРОВЕРКА - используем "текущее" для всех типов
        if тип_квеста in ["убить", "найти", "посетить", "крафт"]:
            текущее = прогресс.get("текущее", 0)
            нужно = цели.get("количество", 1)
            return текущее >= нужно

        elif тип_квеста == "монеты":
            return игрок.get("монета", 0) >= цели.get("количество", 0)

        return False

    def получить_ежедневный_прогресс_строку(self, квест_id, игрок):
        """Возвращает строку прогресса для ежедневного квеста"""
        квест = None
        if hasattr(self, 'ежедневные_квесты'):
            for q in self.ежедневные_квесты:
                if q.get("id") == квест_id:
                    квест = q
                    break

        if not квест:
            return []

        цели = квест.get("цели", {})
        тип_квеста = квест.get("тип", "")

        if квест_id not in игрок.get("ежедневные_квесты_прогресс", {}):
            игрок["ежедневные_квесты_прогресс"][квест_id] = {}

        прогресс = игрок["ежедневные_квесты_прогресс"][квест_id]
        строки = []

        if тип_квеста == "убить":
            враг = цели.get("враг", "любой")
            ключ = f"убить_{враг}"
            текущий = прогресс.get(ключ, 0)
            нужно = цели.get("количество", 1)
            строки.append(f"⚔️ Убить {враг}: {текущий}/{нужно}")

        elif тип_квеста == "найти":
            предмет = цели.get("предмет", "любой")
            ключ = f"найти_{предмет}"
            текущий = прогресс.get(ключ, 0)
            нужно = цели.get("количество", 1)
            строки.append(f"📦 Найти {предмет}: {текущий}/{нужно}")

        elif тип_квеста == "посетить":
            текущий = прогресс.get("посещено", 0)
            нужно = цели.get("количество", 1)
            строки.append(f"🗺️ Посетить локаций: {текущий}/{нужно}")

        elif тип_квеста == "крафт":
            текущий = прогресс.get("крафт", 0)
            нужно = цели.get("количество", 1)
            строки.append(f"🔨 Создать предметов: {текущий}/{нужно}")

        elif тип_квеста == "монеты":
            нужно = цели.get("количество", 100)
            текущий = игрок.get("монета", 0)
            строки.append(f"💰 Собрать монет: {текущий}/{нужно}")

        return строки