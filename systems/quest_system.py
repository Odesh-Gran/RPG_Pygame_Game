import json
import os
import os
print(os.path.exists("data/quests.json"))


class QuestSystem:
    """Система управления квестами"""

    def __init__(self):
        self.квесты = {}
        self.категории = {}
        self.ежедневные_квесты = []
        self.прогресс = {}
        self.ежедневный_прогресс = {}
        self.загрузить_квесты()

    def загрузить_квесты(self, file_path="data/quests.json"):
        """Загружает квесты из JSON"""
        current_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        full_path = os.path.join(current_dir, file_path)

        try:
            with open(full_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
                self.категории = data.get("категории", {})
                self.квесты = data.get("квесты", {})

                # 👇 ВАЖНО! Берём ежедневные ИЗ "квесты"
                self.ежедневные_квесты = self.квесты.get("ежедневные", [])

                # Удаляем ежедневные из квестов (чтобы не мешались)
                if "ежедневные" in self.квесты:
                    del self.квесты["ежедневные"]

                print(f"✅ Загружено {len(self.квесты)} квестов")
                print(f"📂 Категории: {', '.join(self.категории.keys())}")
                print(f"📅 Загружено ЕЖЕДНЕВНЫХ квестов: {len(self.ежедневные_квесты)}")

                if self.ежедневные_квесты:
                    for квест in self.ежедневные_квесты:
                        print(f"   - {квест.get('название', '???')} ({квест.get('id', 'no_id')})")
                else:
                    print("   ⚠️ Ежедневные квесты НЕ ЗАГРУЖЕНЫ!")
                    print("   Проверь структуру JSON: должен быть ключ 'ежедневные' внутри 'квесты'")

                return True
        except FileNotFoundError:
            print(f"❌ Файл {full_path} не найден!")
            return False
        except json.JSONDecodeError as e:
            print(f"❌ Ошибка в JSON: {e}")
            return False

    def получить_квест(self, квест_id):
        """Возвращает данные квеста по ID"""
        return self.квесты.get(квест_id)

    def получить_все_квесты(self):
        """Возвращает все квесты"""
        return self.квесты

    def получить_категории(self):
        """Возвращает все категории"""
        return self.категории

    def получить_квесты_по_категории(self, категория):
        """Возвращает квесты определённой категории"""
        return {id: квест for id, квест in self.квесты.items()
                if квест.get("категория") == категория}

    def получить_доступные_квесты(self, игрок):
        """
        Возвращает квесты, доступные для взятия
        (выполнены зависимости и не завершены/активны)
        """
        доступные = []
        завершенные = игрок.get("завершенные_квесты", [])
        активные = игрок.get("активные_квесты", [])

        for квест_id, данные in self.квесты.items():
            # Пропускаем служебные поля-комментарии
            if квест_id.startswith("_"):
                continue

            # Пропускаем завершённые и активные
            if квест_id in завершенные or квест_id in активные:
                continue

            # Проверяем зависимости
            зависимости = данные.get("зависимости", [])
            все_выполнены = True
            for dep in зависимости:
                if dep not in завершенные:
                    все_выполнены = False
                    break

            if все_выполнены:
                доступные.append(квест_id)

        return доступные

    def добавить_квест(self, игрок, квест_id):
        """Добавляет квест в активные"""
        if квест_id not in self.квесты:
            return False, "❌ Квест не найден"

        if квест_id in игрок.get("активные_квесты", []):
            return False, "❌ Квест уже активен"

        if квест_id in игрок.get("завершенные_квесты", []):
            return False, "❌ Квест уже выполнен"

        данные = self.квесты[квест_id]

        # Проверяем зависимости
        for dep in данные.get("зависимости", []):
            if dep not in игрок.get("завершенные_квесты", []):
                return False, f"❌ Требуется выполнить квест: {self.квесты.get(dep, {}).get('название', dep)}"

        игрок["активные_квесты"].append(квест_id)
        return True, f"📜 Получен квест: {данные['название']}"

    def обновить_прогресс(self, игрок, тип_события, данные_события=None):
        """
        Обновляет прогресс квестов при событиях.
        Возвращает список завершённых квестов.
        """
        print(f"   📜 обновить_прогресс({тип_события}, {данные_события})")

        активные = игрок.get("активные_квесты", [])
        print(f"   Активные квесты: {активные}")

        завершенные = []

        for квест_id in активные:
            print(f"      Проверяем квест: {квест_id}")
            if квест_id not in self.квесты:
                print(f"         ❌ Квест не найден в данных!")
                continue

            данные = self.квесты[квест_id]
            цели = данные.get("цели", {})
            тип_квеста = данные.get("тип", "")

            print(f"         Тип квеста: {тип_квеста}, событие: {тип_события}")

            # Проверяем, подходит ли событие под тип квеста
            if тип_квеста != тип_события:
                print(f"         ⏭️ Тип не совпадает, пропускаем")
                continue

            # Инициализируем прогресс
            if квест_id not in self.прогресс:
                self.прогресс[квест_id] = {}

            # Обновляем прогресс в зависимости от типа
            if тип_квеста == "убить":
                враг = цели.get("враг", "любой")
                if враг == "любой" or враг == данные_события:
                    ключ = f"убить_{враг}"
                    старое = self.прогресс[квест_id].get(ключ, 0)
                    self.прогресс[квест_id][ключ] = старое + 1
                    print(f"         ✅ Прогресс: {старое} -> {self.прогресс[квест_id][ключ]}")

            elif тип_квеста == "найти":
                предмет = цели.get("предмет", "любой")
                if предмет == "любой" or предмет == данные_события:
                    ключ = f"найти_{предмет}"
                    старое = self.прогресс[квест_id].get(ключ, 0)
                    self.прогресс[квест_id][ключ] = старое + 1
                    print(f"         ✅ Прогресс: {старое} -> {self.прогресс[квест_id][ключ]}")

            elif тип_квеста == "посетить":
                локация = цели.get("локация", "любая")
                if локация == "любая" or локация == данные_события:
                    ключ = "посещено"
                    старое = self.прогресс[квест_id].get(ключ, 0)
                    self.прогресс[квест_id][ключ] = старое + 1
                    print(f"         ✅ Прогресс: {старое} -> {self.прогресс[квест_id][ключ]}")

            # Проверяем выполнение
            if self.проверить_выполнение(квест_id, игрок):
                print(f"КВЕСТ ВЫПОЛНЕН! {квест_id}")
                игрок["активные_квесты"].remove(квест_id)
                игрок["завершенные_квесты"].append(квест_id)
                завершенные.append(квест_id)
                self.выдать_награду(игрок, данные.get("награда", {}))

                следующий = данные.get("следующий")
                if следующий:
                    успех, сообщение = self.добавить_квест(игрок, следующий)
                    if успех:
                        print(f"         ➡️ {сообщение}")

        print(f"   📊 Завершено квестов: {завершенные}")
        return завершенные

    def проверить_выполнение(self, квест_id, игрок):
        """Проверяет, выполнены ли все цели квеста"""
        if квест_id not in self.квесты:
            return False

        данные = self.квесты[квест_id]
        цели = данные.get("цели", {})
        тип_квеста = данные.get("тип", "")

        if квест_id not in self.прогресс:
            return False

        прогресс = self.прогресс[квест_id]

        if тип_квеста == "убить":
            враг = цели.get("враг", "любой")
            ключ = f"убить_{враг}"
            return прогресс.get(ключ, 0) >= цели.get("количество", 1)

        elif тип_квеста == "найти":
            предмет = цели.get("предмет", "любой")
            ключ = f"найти_{предмет}"
            return прогресс.get(ключ, 0) >= цели.get("количество", 1)

        elif тип_квеста == "посетить":
            return прогресс.get("посещено", 0) >= цели.get("количество", 1)

        elif тип_квеста == "уровень":
            return прогресс.get("уровень", False)

        elif тип_квеста == "крафт":
            return прогресс.get("крафт", 0) >= цели.get("количество", 1)

        elif тип_квеста == "монеты":
            return прогресс.get("монеты", False)

        return False

    def выдать_награду(self, игрок, награда):
        """Выдаёт награду за квест"""
        from игрок import добавить_опыт

        print(f"\n🎁 ВЫПОЛНЕН КВЕСТ! Награда:")

        if "опыт" in награда:
            добавить_опыт(награда["опыт"])
            print(f"   ⭐ Опыт +{награда['опыт']}")

        if "монеты" in награда:
            игрок["монета"] = игрок.get("монета", 0) + награда["монеты"]
            print(f"   🪙 Монеты +{награда['монеты']}")

        if "предметы" in награда:
            for предмет in награда["предметы"]:
                игрок["инвентарь"].append(предмет)
                print(f"   📦 Получен предмет: {предмет}")

        print("")

    def получить_прогресс_строку(self, квест_id, игрок=None):
        """Возвращает строки с прогрессом квеста для отображения"""
        if квест_id not in self.квесты:
            return []

        данные = self.квесты[квест_id]
        цели = данные.get("цели", {})
        тип_квеста = данные.get("тип", "")

        if квест_id not in self.прогресс:
            self.прогресс[квест_id] = {}

        прогресс = self.прогресс[квест_id]
        строки = []

        if тип_квеста == "убить":
            враг = цели.get("враг", "любой")
            ключ = f"убить_{враг}"
            текущий = прогресс.get(ключ, 0)
            нужно = цели.get("количество", 1)
            строки.append(f"⚔️ Убить {враг}: {текущий}/{нужно}")

        elif тип_квеста == "найти":
            предмет = цели.get("предмет", "любой")
            ключ = f"найти_{предмет}"
            текущий = прогресс.get(ключ, 0)
            нужно = цели.get("количество", 1)
            строки.append(f"📦 Найти {предмет}: {текущий}/{нужно}")

        elif тип_квеста == "посетить":
            текущий = прогресс.get("посещено", 0)
            нужно = цели.get("количество", 1)
            строки.append(f"🗺️ Посетить локаций: {текущий}/{нужно}")

        elif тип_квеста == "уровень":
            нужно = цели.get("уровень", 1)
            статус = "✅" if прогресс.get("уровень", False) else "❌"
            строки.append(f"📊 Достичь уровня {нужно}: {статус}")

        elif тип_квеста == "крафт":
            текущий = прогресс.get("крафт", 0)
            нужно = цели.get("количество", 1)
            строки.append(f"🔨 Создать предметов: {текущий}/{нужно}")

        elif тип_квеста == "монеты":
            нужно = цели.get("количество", 500)
            # 👇 ИСПРАВЛЕНО: проверяем, передан ли игрок
            if игрок:
                текущий = игрок.get("монета", 0)
            else:
                текущий = 0
            строки.append(f"💰 Собрать монет: {текущий}/{нужно}")

        return строки

