        if игрок.get("ежедневные_квесты_дата") != сегодня:
            игрок["ежедневные_квесты"] = []
            игрок["ежедневные_квесты_прогресс"] = {}
            игрок["ежедневные_квесты_дата"] = сегодня

            # Берём 3 случайных ежедневных квеста
            import random
            if hasattr(self, 'ежедневные_квесты'):
                все_квесты = self.ежедневные_квесты.copy()
