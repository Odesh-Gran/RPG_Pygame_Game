def craft_item(game, название, рецепт):
    """
    Универсальная функция крафта.
    Возвращает True, если крафт успешен, иначе False.
    """
    print("\n" + "=" * 40)
    print("КРАФТ ПРЕДМЕТА:", название)
    print("=" * 40)

    print(f"Тип рецепта: {type(рецепт)}")
    print(f"Рецепт: {рецепт}")

    # Определяем тип рецепта
    if isinstance(рецепт, dict) and 'ресурсы' in рецепт:
        ресурсы = рецепт['ресурсы']
        количество = рецепт.get('количество', 1)
        print(f"Словарь-рецепт. Ресурсы: {ресурсы}, количество: {количество}")
    elif isinstance(рецепт, list):
        ресурсы = рецепт
        количество = 1
        print(f"Список ресурсов: {ресурсы}")
    else:
        print(f"Ошибка: непонятный тип рецепта {type(рецепт)}")
        return False

    print(f"\n🎒 Инвентарь ДО: {game.игрок['инвентарь']}")

    # Проверяем наличие ресурсов
    инвентарь_копия = game.игрок["инвентарь"].copy()

    for ресурс in ресурсы:
        if ресурс in инвентарь_копия:
            индекс = инвентарь_копия.index(ресурс)
            инвентарь_копия.pop(индекс)
            print(f"  ✅ Найден {ресурс}")
        else:
            print(f"  ❌ НЕ ХВАТАЕТ {ресурс}!")
            print(f"  Доступные ресурсы: {set(game.игрок['инвентарь'])}")
            return False

    print(f"\n Все ресурсы есть!")

    # Удаляем ресурсы
    for ресурс in ресурсы:
        game.игрок["инвентарь"].remove(ресурс)
        print(f"  🗑️ Удален {ресурс}")

    # Добавляем результат
    for i in range(количество):
        game.игрок["инвентарь"].append(название)
        print(f"  ➕ Добавлен {название} #{i + 1}")

    print(f"\n🎒 Инвентарь ПОСЛЕ: {game.игрок['инвентарь']}")
    print("=" * 40)
    print("✅ КРАФТ УСПЕШНО ЗАВЕРШЕН!")
    print("=" * 40)

    game.add_to_log(f"Создан {название} x{количество}")

    # ===== ОБНОВЛЯЕМ ЕЖЕДНЕВНЫЙ КВЕСТ "КУЗНЕЦ ДНЯ" =====
    if hasattr(game, 'quest_system') and hasattr(game, 'игрок'):
        завершенные = game.quest_system.обновить_ежедневный_прогресс(
            game.игрок,
            "крафт",
            название
        )
        if завершенные:
            for квест_id in завершенные:
                for q in game.quest_system.ежедневные_квесты:
                    if q.get("id") == квест_id:
                        game.add_to_log(f"📅 Ежедневный квест выполнен: {q['название']}")
                        break

    return True