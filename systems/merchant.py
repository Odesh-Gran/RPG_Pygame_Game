def trade_buy_item(game, предмет, количество):
    """Купить предметы (безлимитная версия)"""
    if предмет not in game.trade_goods:
        return

    данные = game.trade_goods[предмет]
    монеты = game.игрок.get('монета', 0)

    # Просто покупаем сколько просят (без проверки лимитов)
    можно_купить = количество
    общая_цена = данные['цена'] * можно_купить

    # Проверяем только деньги
    if монеты < общая_цена:
        game.add_to_log(f"Нужно {общая_цена} монет!")
        return

    # Покупаем
    game.игрок['монета'] = монеты - общая_цена
    for _ in range(можно_купить):
        game.inventory.add_item(предмет)

    game.add_to_log(f"Куплено {можно_купить} {предмет} за {общая_цена}!")


def trade_sell_item(game, предмет, количество, цена):
    """Продать предметы"""
    if предмет not in game.игрок["инвентарь"]:
        return

    # Проверяем, сколько есть
    есть = game.игрок["инвентарь"].count(предмет)
    можно_продать = min(есть, количество)

    if можно_продать == 0:
        return

    # Продаём
    for _ in range(можно_продать):
        game.inventory.remove_item(предмет)

    выручка = можно_продать * цена
    game.игрок['монета'] = game.игрок.get('монета', 0) + выручка

    game.add_to_log(f"Продано {можно_продать} {предмет} за {выручка} монет!")
    game.add_to_log(f"Продан {предмет} x{можно_продать}")