# ========== ФУНКЦИИ ДЛЯ РАБОТЫ С ВРАГАМИ ==========

def получить_лесного_врага(уровень_игрока):
    """
    Возвращает подходящего врага для леса в зависимости от уровня игрока

    Args:
        уровень_игрока: уровень игрока

    Returns:
        tuple: (имя_врага, данные_врага)
    """
    import random

    # Сортируем врагов по уровню
    доступные_враги = []
    for имя, данные in ЛЕСНЫЕ_ВРАГИ.items():
        if данные["уровень"] <= уровень_игрока + 2:  # Враги не более чем на 2 уровня выше
            доступные_враги.append((имя, данные))

    if not доступные_враги:
        доступные_враги = [("лесной_гоблин", ЛЕСНЫЕ_ВРАГИ["лесной_гоблин"])]

    # Веса для разных типов врагов
    веса = []
    for имя, данные in доступные_враги:
        if данные["уровень"] <= уровень_игрока - 2:
            вес = 30  # слабые враги реже
        elif данные["уровень"] <= уровень_игрока:
            вес = 60  # враги своего уровня чаще
        else:
            вес = 10  # сильные враги редко
        веса.append(вес)

    # Выбираем врага с учётом весов
    выбранный = random.choices(доступные_враги, weights=веса, k=1)[0]

    return выбранный[0], выбранный[1]


def получить_босса(название):
    """
    Возвращает данные босса по названию

    Args:
        название: название босса

    Returns:
        dict: данные босса
    """
