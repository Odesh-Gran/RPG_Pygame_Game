def получить_случайного_врага(локация="лес"):
    """
    Возвращает случайного врага для указанной локации

    Args:
        локация: тип локации ("лес" или "обычный")

    Returns:
        tuple: (имя_врага, данные_врага)
    """
    import random

    if локация == "лес":
        доступные = list(ЛЕСНЫЕ_ВРАГИ.items())
    else:
        # Фильтруем обычных врагов (не из леса)
        доступные = [(имя, данные) for имя, данные in враги.items()
                     if имя not in ЛЕСНЫЕ_ВРАГИ and имя not in ЛЕСНЫЕ_БОССЫ]

    if not доступные:
        доступные = [("таракан", враги["таракан"])]

    return random.choice(доступные)