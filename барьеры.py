def проверить_доступность_локации(название_локации, инвентарь_словарь):
    """
    Проверяет, доступна ли локация для перехода.
    Возвращает: (доступна, причина_блокировки, подсказка)
    """
    # Если барьер уже открыт — всегда доступно
    if is_barrier_open(название_локации):
        return True, None, None

    # Ищем барьер, который блокирует эту локацию
    for локация_источник, барьеры_локации in барьеры.items():
        for барьер_ключ, барьер in барьеры_локации.items():
            if барьер["локация_назначения"] == название_локации:
                # Нашли барьер, который ведёт в эту локацию
                нужный_предмет = барьер["требуется"]
                нужное_количество = барьер.get("требуется_количество", 1)

                if инвентарь_словарь.get(нужный_предмет, 0) >= нужное_количество:
                    return True, None, None
                else:
                    return False, барьер["текст"], барьер.get("подсказка", "")

    # Нет барьера — локация доступна
    return True, None, None


def проверить_барьеры_в_локации(название_локации, инвентарь_словарь):
    """
    Проверяет барьеры в локации для панели выходов.
    Возвращает: (доступные_выходы, заблокированные_выходы)
    """
    import локации

    локация_данные = локации.локации[название_локации]
    доступные_выходы = []
    заблокированные_выходы = []

    локальные_барьеры = барьеры.get(название_локации, {})

    for ключ, выход in локация_данные["выходы"].items():
        название_выхода = выход["название"]

        # Ищем барьер для этого выхода
        барьер = None
        барьер_ключ = None
        for б_ключ, б_данные in локальные_барьеры.items():
            if б_данные["открывает"] == название_выхода:
                барьер = б_данные
                барьер_ключ = б_ключ
                break

        if барьер:
            # Выход заблокирован барьером

            # Если барьер уже открыт — выход свободен
            if is_barrier_open(название_выхода):
                доступные_выходы.append({
                    "ключ": ключ,
                    "название": название_выхода,
                    "текст": выход["текст"],
                    "заблокирован": False
                })
                continue

            нужный_предмет = барьер["требуется"]
            нужное_количество = барьер.get("требуется_количество", 1)

            # Проверяем, есть ли у игрока нужный предмет
            if инвентарь_словарь.get(нужный_предмет, 0) >= нужное_количество:
                заблокированные_выходы.append({
                    "ключ": ключ,
                    "название": название_выхода,
                    "текст": выход["текст"],
                    "заблокирован": True,
                    "может_открыть": True,
                    "барьер": барьер,
                    "барьер_ключ": барьер_ключ
                })
            else:
                заблокированные_выходы.append({
                    "ключ": ключ,
                    "название": название_выхода,
                    "текст": выход["текст"],
                    "заблокирован": True,
                    "может_открыть": False,
                    "барьер": барьер,
                    "чего_не_хватает": нужный_предмет,
                    "сколько_нужно": нужное_количество
                })
        else:
            # Выход свободен
            доступные_выходы.append({
                "ключ": ключ,
                "название": название_выхода,
                "текст": выход["текст"],
                "заблокирован": False
            })

    return доступные_выходы, заблокированные_выходы


def открыть_локацию_через_барьер(текущая_локация, целевая_локация, инвентарь_словарь):
    """
    Открывает барьер при клике на карте.
    Возвращает: (успех, сообщение, обновлённый_инвентарь)
    """
    print(f"\n🔍 ОТКРЫТИЕ БАРЬЕРА: {текущая_локация} -> {целевая_локация}")
    print(f"📦 Инвентарь (словарь): {инвентарь_словарь}")

    # Если барьер уже открыт
    if is_barrier_open(целевая_локация):
        print(f"✅ Барьер для {целевая_локация} уже открыт")
        return True, "Путь уже открыт.", инвентарь_словарь

    # Ищем барьер
    for локация_источник, барьеры_локации in барьеры.items():
        for барьер_ключ, барьер in барьеры_локации.items():
            if барьер["локация_назначения"] == целевая_локация:
                нужный_предмет = барьер["требуется"]
                нужное_количество = барьер.get("требуется_количество", 1)

                print(f"🔑 Нужно: {нужный_предмет} x{нужное_количество}")
                print(f"📦 Есть в инвентаре: {инвентарь_словарь.get(нужный_предмет, 0)}")

                есть = инвентарь_словарь.get(нужный_предмет, 0)

                if есть >= нужное_количество:
                    # Списываем предмет
                    инвентарь_словарь[нужный_предмет] -= нужное_количество
                    if инвентарь_словарь[нужный_предмет] == 0:
                        del инвентарь_словарь[нужный_предмет]

                    # Запоминаем, что барьер открыт
                    открытые_барьеры.add(целевая_локация)
                    # сохранить_барьеры()  # <-- ЗАКОММЕНТИРОВАНО, теперь сохраняется в сейве

                    print(f"✅ БАРЬЕР ОТКРЫТ! {нужный_предмет} списан. Осталось: {инвентарь_словарь.get(нужный_предмет, 0)}")
                    текст_открытия = барьер.get("альтернативный_текст",
                                                f"Ты используешь {нужный_предмет}. Путь открыт!")
                    return True, текст_открытия, инвентарь_словарь
                else:
                    print(f"   ❌ Не хватает {нужный_предмет}! Нужно {нужное_количество}, есть {есть}")
                    return False, f"У тебя нет {нужный_предмет} ({нужное_количество} шт).", инвентарь_словарь

    print(f"❌ Барьер для {целевая_локация} не найден!")
    return False, "Нет барьера, блокирующего эту локацию.", инвентарь_словарь


def открыть_барьер(название_локации, барьер_ключ, инвентарь_словарь):
    """
    Открывает барьер в текущей локации (для панели выходов).
    Возвращает: (успех, сообщение, новая_локация, обновлённый_инвентарь)
    """
    print(f"\n🔓 ОТКРЫТИЕ БАРЬЕРА: {название_локации} -> {барьер_ключ}")
    print(f"📦 Инвентарь: {инвентарь_словарь}")

    локальные_барьеры = барьеры.get(название_локации, {})

    барьер = локальные_барьеры.get(барьер_ключ)
    if not барьер:
        return False, "Здесь нет такого барьера.", None, инвентарь_словарь

    целевая_локация = барьер["локация_назначения"]

    # Если барьер уже открыт
    if is_barrier_open(целевая_локация):
        return True, "Путь уже открыт.", целевая_локация, инвентарь_словарь

    нужный_предмет = барьер["требуется"]
    нужное_количество = барьер.get("требуется_количество", 1)

    print(f"🔑 Нужно: {нужный_предмет} x{нужное_количество}")
    print(f"📦 Есть: {инвентарь_словарь.get(нужный_предмет, 0)}")

    if инвентарь_словарь.get(нужный_предмет, 0) < нужное_количество:
        return False, f"У тебя нет {нужный_предмет} ({нужное_количество} шт).", None, инвентарь_словарь

    # Списываем предмет
    инвентарь_словарь[нужный_предмет] -= нужное_количество
    if инвентарь_словарь[нужный_предмет] == 0:
        del инвентарь_словарь[нужный_предмет]

    # Запоминаем, что барьер открыт
    открытые_барьеры.add(целевая_локация)
    # сохранить_барьеры()  # <-- ЗАКОММЕНТИРОВАНО, теперь сохраняется в сейве

    print(f"✅ БАРЬЕР ОТКРЫТ! {нужный_предмет} списан.")
    текст_открытия = барьер.get("альтернативный_текст", f"Ты используешь {нужный_предмет}. Барьер исчезает!")

    return True, текст_открытия, целевая_локация, инвентарь_словарь


def получить_подсказку_для_локации(целевая_локация):
    """
    Возвращает подсказку, как открыть заблокированную локацию.
    """
    if is_barrier_open(целевая_локация):
        return None

    for локация_источник, барьеры_локации in барьеры.items():
        for барьер_ключ, барьер in барьеры_локации.items():
            if барьер["локация_назначения"] == целевая_локация:
                return барьер.get("подсказка", "Нужно найти способ открыть этот путь.")

    return None


def получить_подсказку(название_локации, инвентарь_словарь):
    """
    Возвращает подсказку для ближайшего неоткрытого барьера в локации.
    """
    _, заблокированные = проверить_барьеры_в_локации(название_локации, инвентарь_словарь)

    if not заблокированные:
        return "Здесь больше нет преград."

    for барьер in заблокированные:
        if not барьер["может_открыть"]:
            return барьер["барьер"].get("подсказка", "Осмотрись внимательнее...")

    return "Ты можешь открыть один из выходов!"